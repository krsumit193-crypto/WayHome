#!/usr/bin/env python3
"""
Convert timetable CSVs into a Flyway migration (SQL) for Railhop.

Usage:
  python3 tools/import_timetable.py data/sample > backend/src/main/resources/db/migration/V3__import.sql

Input folder must contain:
  stations.csv  code,name,lat,lng
  trains.csv    number,name,runs_on          runs_on = 7 chars Mon..Sun, 1 = runs (e.g. 1111100)
  stops.csv     train_number,seq,station_code,arrival,departure,day,distance_km
                arrival/departure are HH:MM (empty at origin/destination),
                day = days since the train's origin day (0 = same day, 1 = next day ...)

Check the license of whatever dataset you use before shipping it.
"""
import csv
import sys
from pathlib import Path


def sql(value):
    if value is None or value == "":
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def minutes(hhmm, day):
    if not hhmm:
        return "NULL"
    h, m = hhmm.split(":")
    return str(int(day) * 1440 + int(h) * 60 + int(m))


def mask(runs_on):
    if len(runs_on) != 7 or set(runs_on) - {"0", "1"}:
        raise ValueError(f"runs_on must be 7 digits of 0/1, got {runs_on!r}")
    return sum(1 << i for i, c in enumerate(runs_on) if c == "1")


def main(folder):
    base = Path(folder)
    out = ["-- Generated by tools/import_timetable.py"]

    with open(base / "stations.csv", newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            lat = r["lat"] or "NULL"
            lng = r["lng"] or "NULL"
            out.append(
                f"INSERT INTO station (code, name, lat, lng) VALUES ({sql(r['code'])}, {sql(r['name'])}, {lat}, {lng}) "
                "ON CONFLICT (code) DO NOTHING;"
            )

    with open(base / "trains.csv", newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            out.append(
                f"INSERT INTO train (number, name, runs_on_mask) VALUES ({sql(r['number'])}, {sql(r['name'])}, {mask(r['runs_on'])}) "
                "ON CONFLICT (number) DO NOTHING;"
            )

    with open(base / "stops.csv", newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            day = r["day"] or "0"
            out.append(
                "INSERT INTO train_stop (train_number, seq, station_code, arrival_min, departure_min, distance_km) VALUES "
                f"({sql(r['train_number'])}, {int(r['seq'])}, {sql(r['station_code'])}, "
                f"{minutes(r['arrival'], day)}, {minutes(r['departure'], day)}, {int(r['distance_km'] or 0)}) "
                "ON CONFLICT (train_number, seq) DO NOTHING;"
            )

    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
